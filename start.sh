#!/bin/bash

echo "🚀 Starting Qwen Math Evaluation UI..."

# Check if we're in the right directory
if [ ! -f "backend/app/main.py" ]; then
    echo "❌ Error: Please run this script from the reasoning-models-eval directory"
    exit 1
fi

# Function to find an available port starting from a given port
find_available_port() {
    local start_port=$1
    local port=$start_port
    local max_attempts=10
    
    while [ $port -lt $((start_port + max_attempts)) ]; do
        # Check if port is in use (try both netstat and ss)
        if command -v netstat &> /dev/null; then
            if ! netstat -tuln | grep -q ":$port "; then
                echo $port
                return 0
            fi
        elif command -v ss &> /dev/null; then
            if ! ss -tuln | grep -q ":$port "; then
                echo $port
                return 0
            fi
        else
            # Fallback: try to bind to the port
            if timeout 0.1 bash -c "echo > /dev/tcp/localhost/$port" 2>/dev/null; then
                port=$((port + 1))
                continue
            else
                echo $port
                return 0
            fi
        fi
        port=$((port + 1))
    done
    
    # If no port found, return the original port
    echo $start_port
    return 1
}

# Find an available backend port
BACKEND_PORT=$(find_available_port 8000)
echo "📡 Using backend port: $BACKEND_PORT"

# Create or update frontend config file with dynamic port
CONFIG_FILE="frontend/config.js"
cat > "$CONFIG_FILE" << EOF
// Auto-generated configuration file
// This file is automatically generated by start.sh - DO NOT EDIT MANUALLY
window.API_BASE = 'http://localhost:$BACKEND_PORT';
window.WS_BASE = 'ws://localhost:$BACKEND_PORT';
console.log('📡 Backend configured on port $BACKEND_PORT');
EOF

# Start backend
echo "📡 Starting backend server on http://localhost:$BACKEND_PORT..."
cd backend
uvicorn app.main:app --reload --host 0.0.0.0 --port $BACKEND_PORT &
BACKEND_PID=$!
cd ..

# Wait a moment for backend to start
sleep 3

# Check if backend started successfully
if ! ps -p $BACKEND_PID > /dev/null; then
    echo "❌ Error: Backend server failed to start"
    rm -f "$CONFIG_FILE"
    exit 1
fi

# Start frontend
echo "🌐 Starting frontend server on http://localhost:3000..."
cd frontend
python3 -m http.server 3000 &
FRONTEND_PID=$!
cd ..

echo ""
echo "✅ Qwen Math Evaluation UI is running!"
echo "   Backend:  http://localhost:$BACKEND_PORT"
echo "   Frontend: http://localhost:3000"
echo ""
echo "Press Ctrl+C to stop both servers"

# Function to cleanup on exit
cleanup() {
    echo ""
    echo "🛑 Stopping servers..."
    kill $BACKEND_PID 2>/dev/null
    kill $FRONTEND_PID 2>/dev/null
    rm -f "$CONFIG_FILE"
    exit 0
}

# Set up signal handlers
trap cleanup SIGINT SIGTERM

# Wait for background processes
wait 
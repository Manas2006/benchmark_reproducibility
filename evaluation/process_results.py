#!/usr/bin/env python3
"""
Post-processing script to calculate final metrics from raw logprobs data.

This script reads the output from main.py and computes final metrics
(chosen token probability, entropy, etc.) from the saved log probabilities.
"""

import argparse
import json
import torch
import math
from pathlib import Path
from typing import List, Dict, Any
from transformers import AutoTokenizer


def parse_args():
    parser = argparse.ArgumentParser(description="Process results with raw logprobs to calculate final metrics")
    parser.add_argument("--input_file", required=True, type=str, help="Path to JSONL file generated by main.py")
    parser.add_argument("--model_name_or_path", required=True, type=str, help="Model name or path for tokenizer")
    parser.add_argument("--output_file", type=str, help="Output file path (default: input_file_processed.jsonl)")
    return parser.parse_args()


def calculate_entropy(logprobs_dict: Dict[int, float]) -> float:
    """Calculate Shannon entropy from log probabilities dictionary."""
    if not logprobs_dict:
        return 0.0
    
    # Convert log probabilities to probabilities
    logprobs_tensor = torch.tensor(list(logprobs_dict.values()))
    probs_tensor = torch.exp(logprobs_tensor)
    
    # Normalize to ensure they sum to 1, correcting for potential float errors
    probs_tensor = probs_tensor / probs_tensor.sum()
    
    # Calculate Shannon entropy: -sum(p * log(p))
    # Use torch.log to avoid numerical issues with log(0)
    log_probs = torch.log(probs_tensor + 1e-10)  # Add small epsilon to avoid log(0)
    entropy = -torch.sum(probs_tensor * log_probs).item()
    
    return entropy


def calculate_chosen_token_prob(logprobs_dict: Dict[int, float], chosen_token_id: int) -> float:
    """Calculate probability of the chosen token."""
    if chosen_token_id in logprobs_dict:
        # Convert log probability to probability
        return math.exp(logprobs_dict[chosen_token_id])
    return 0.0


def calculate_correct_token_prob(logprobs_dict: Dict[int, float], correct_token_id: int) -> float:
    """Calculate probability of the correct token."""
    if correct_token_id in logprobs_dict:
        # Convert log probability to probability
        return math.exp(logprobs_dict[correct_token_id])
    return 0.0


def get_correct_token_ids(sample: Dict[str, Any], tokenizer) -> List[int]:
    """Extract correct token IDs from ground truth."""
    gt = sample.get('gt', '')
    gt_cot = sample.get('gt_cot', '')
    
    # Use gt_cot if available, otherwise use gt
    correct_text = gt_cot if gt_cot else str(gt)
    
    if correct_text:
        return tokenizer.encode(correct_text, add_special_tokens=False)
    return []


def process_sample(sample: Dict[str, Any], tokenizer) -> Dict[str, Any]:
    """Process a single sample to calculate metrics from raw logprobs."""
    
    # Create a copy to avoid modifying the original
    processed_sample = sample.copy()
    
    # Check if this sample has raw logprobs data
    raw_logprobs = sample.get('raw_logprobs')
    generated_token_ids = sample.get('generated_token_ids')
    
    if not raw_logprobs or not generated_token_ids:
        # No raw logprobs data, return sample as-is
        return processed_sample
    
    # Get correct token IDs for this sample
    correct_token_ids = get_correct_token_ids(sample, tokenizer)
    
    # Initialize metric lists
    chosen_token_probs = []
    correct_token_probs = []
    entropies = []
    
    # Process each step in the generation
    for step_idx, step_logprobs in enumerate(raw_logprobs):
        if step_logprobs is None:
            # Skip steps with no logprobs
            chosen_token_probs.append(None)
            correct_token_probs.append(None)
            entropies.append(None)
            continue
            
        # Calculate entropy for this step
        entropy = calculate_entropy(step_logprobs)
        entropies.append(entropy)
        
        # Calculate chosen token probability
        if step_idx < len(generated_token_ids):
            chosen_token_id = generated_token_ids[step_idx]
            chosen_prob = calculate_chosen_token_prob(step_logprobs, chosen_token_id)
            chosen_token_probs.append(chosen_prob)
        else:
            chosen_token_probs.append(None)
        
        # Calculate correct token probability
        if step_idx < len(correct_token_ids):
            correct_token_id = correct_token_ids[step_idx]
            correct_prob = calculate_correct_token_prob(step_logprobs, correct_token_id)
            correct_token_probs.append(correct_prob)
        else:
            correct_token_probs.append(None)
    
    # Add calculated metrics to the sample - use standard field names for compatibility
    processed_sample['chosen_token_probs'] = chosen_token_probs
    processed_sample['correct_token_probs'] = correct_token_probs  
    processed_sample['entropies'] = entropies
    
    # Also add epoch-based format for compatibility with existing plotting code
    processed_sample['chosen_token_probs'] = {"epoch_0": chosen_token_probs}
    processed_sample['correct_token_probs'] = {"epoch_0": correct_token_probs}
    processed_sample['entropies'] = {"epoch_0": entropies}
    
    # Calculate aggregate statistics
    valid_chosen_probs = [p for p in chosen_token_probs if p is not None]
    valid_correct_probs = [p for p in correct_token_probs if p is not None]
    valid_entropies = [e for e in entropies if e is not None]
    
    if valid_chosen_probs:
        processed_sample['avg_chosen_token_prob'] = sum(valid_chosen_probs) / len(valid_chosen_probs)
        processed_sample['min_chosen_token_prob'] = min(valid_chosen_probs)
        processed_sample['max_chosen_token_prob'] = max(valid_chosen_probs)
    
    if valid_correct_probs:
        processed_sample['avg_correct_token_prob'] = sum(valid_correct_probs) / len(valid_correct_probs)
        processed_sample['min_correct_token_prob'] = min(valid_correct_probs)
        processed_sample['max_correct_token_prob'] = max(valid_correct_probs)
    
    if valid_entropies:
        processed_sample['avg_entropy'] = sum(valid_entropies) / len(valid_entropies)
        processed_sample['min_entropy'] = min(valid_entropies)
        processed_sample['max_entropy'] = max(valid_entropies)
    
    return processed_sample


def main():
    args = parse_args()
    
    input_path = Path(args.input_file)
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    # Determine output file path
    if args.output_file:
        output_path = Path(args.output_file)
    else:
        output_path = input_path.parent / f"{input_path.stem}_processed{input_path.suffix}"
    
    # Load tokenizer
    print(f"Loading tokenizer from {args.model_name_or_path}...")
    tokenizer = AutoTokenizer.from_pretrained(args.model_name_or_path, trust_remote_code=True)
    
    # Process the input file
    print(f"Processing {input_path}...")
    processed_samples = []
    samples_with_logprobs = 0
    total_samples = 0
    
    with open(input_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
                
            try:
                sample = json.loads(line)
                total_samples += 1
                
                # Process the sample
                processed_sample = process_sample(sample, tokenizer)
                processed_samples.append(processed_sample)
                
                # Count samples with logprobs
                if sample.get('raw_logprobs'):
                    samples_with_logprobs += 1
                    
            except json.JSONDecodeError as e:
                print(f"Warning: Skipping malformed JSON on line {line_num}: {e}")
                continue
    
    # Save processed results
    print(f"Saving processed results to {output_path}...")
    with open(output_path, 'w', encoding='utf-8') as f:
        for sample in processed_samples:
            f.write(json.dumps(sample) + '\n')
    
    # Print summary
    print(f"\nProcessing complete!")
    print(f"Total samples processed: {total_samples}")
    print(f"Samples with raw logprobs: {samples_with_logprobs}")
    print(f"Output saved to: {output_path}")
    
    if samples_with_logprobs > 0:
        print(f"\nMetrics calculated for {samples_with_logprobs} samples:")
        print("- chosen_token_probs_calculated: Probability of tokens chosen by the model")
        print("- correct_token_probs: Probability of correct tokens from ground truth")
        print("- entropies_calculated: Shannon entropy for each generation step")
        print("- avg_*/min_*/max_* variants: Aggregate statistics for each metric")


if __name__ == "__main__":
    main()
